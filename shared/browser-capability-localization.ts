export function browserCapabilityDisplay(id: string, locale: 'zh-CN' | 'ja') {
  if (id === 'browser' || id === 'realmflow.builtin.browser') {
    return locale === 'zh-CN'
      ? { name: '浏览器', description: '本地浏览器会话、网页操作与授权目录内的产物管理。' }
      : { name: 'ブラウザー', description: 'ローカルブラウザー、ページ操作、許可された場所での成果物管理。' }
  }
  if (!id.startsWith('builtin.browser.')) return undefined
  const action = id.slice('builtin.browser.'.length) as keyof typeof names['zh-CN']
  if (!Object.hasOwn(names[locale], action)) return undefined
  const [name, description] = names[locale][action]
  return { name, description }
}
